import assert from 'node:assert/strict';
import {INCOTERMS,isCompatible,getIncoterm,allocate} from '../lib/incoterms.ts';
import {calculateDestinationTax,calculateBrazilImport,hasRate} from '../lib/calc.ts';
assert.equal(INCOTERMS.length,11);
assert.equal(new Set(INCOTERMS.map(x=>x.code)).size,11);
assert.equal(INCOTERMS.filter(x=>x.modes==='sea').length,4);
assert.equal(INCOTERMS.filter(x=>x.modes==='any').length,7);
assert.equal(isCompatible('FOB','Aéreo'),false);
assert.equal(isCompatible('CIP','Aéreo'),true);
assert.equal(getIncoterm('DPU').sellerCosts.includes('unloading'),true);
assert.equal(getIncoterm('DDP').importClearance,'seller');
assert.equal(getIncoterm('CPT').risk.includes('não na chegada'),true);
assert.deepEqual(allocate(getIncoterm('CIF'),{origin:100,loading:50,freight:400,insurance:60,lastMile:50,unloading:20,tax:80}),{seller:610,buyer:150});
assert.equal(calculateDestinationTax(1000,'10','20').total,320);
assert.equal(calculateDestinationTax(1000,'','20').complete,false);
assert.equal(calculateBrazilImport(1000,{ii:'10',ipi:'5',pis:'1',cofins:'4',icms:'18'}).complete,true);
assert.equal(calculateBrazilImport(1000,{ii:'10',ipi:'5',pis:'1',cofins:'4',icms:'100'}).complete,false);
assert.equal(hasRate('0'),true);
assert.equal(hasRate(''),false);
assert.equal(hasRate('-5'),false);
console.log('PASS: 16 verificações de Incoterms e cálculos didáticos.');
